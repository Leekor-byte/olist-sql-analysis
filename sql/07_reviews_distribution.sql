-- =============================================================
-- Раздел 6. Распределение оценок клиентов
--
-- Вопрос: как распределены оценки 1-5?
--
-- Результат:
--   - 57.8% — оценка 5 (хорошо для e-commerce)
--   - 11.5% — оценка 1 (высокий негатив)
--   - 5 и 4 вместе: 77%, 1 и 2 вместе: 14.7%
-- =============================================================

SELECT 
    review_score,
    COUNT(*) AS reviews_count,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM order_reviews), 1) AS pct
FROM order_reviews
GROUP BY review_score
ORDER BY review_score;